const setLanguage = (language) => {
  const selected = Object.hasOwn(translations, language) ? language : "en";
  currentLanguage = selected;
  const content = translations[selected];
  document.documentElement.lang = selected;
  const title = content[document.body.dataset.titleKey || "homeTitle"];
  if (typeof title === "string") document.title = title;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = content[element.dataset.i18n];
    if (typeof value === "string") element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = content[element.dataset.i18nAlt];
    if (typeof value === "string") element.alt = value;
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const value = content[element.dataset.i18nAriaLabel];
    if (typeof value === "string") element.setAttribute("aria-label", value);
  });
  document.querySelectorAll(".language-switch").forEach((switcher) => {
    const previous = switcher.dataset.currentOption || switcher.querySelector(".language-button:checked")?.getAttribute("c-option") || "1";
    const target = switcher.querySelector(`.language-button[value="${selected}"]`);
    if (target && !target.checked) switcher.setAttribute("c-previous", previous);
    if (target) {
      target.checked = true;
      switcher.dataset.currentOption = target.getAttribute("c-option") || "1";
      switcher.dataset.activeOption = switcher.dataset.currentOption;
    }
  });
  saveSetting("language", selected);
  updatePageLinks();
};

const applyTheme = (theme) => {
  const resolved = theme === "system" ? (systemTheme.matches ? "dark" : "light") : theme;
  document.documentElement.dataset.theme = resolved;
  document.documentElement.dataset.themePreference = theme;
  if (themeButton) themeButton.querySelector(".theme-icon").textContent = resolved === "dark" ? "☀" : "☾";
  if (themeColor) themeColor.content = resolved === "dark" ? "#09090b" : "#f5f5f7";
  updatePageLinks();
};

