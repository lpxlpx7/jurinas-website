const menuButton = document.querySelector(".menu-button");
const mobileMenu = document.querySelector(".mobile-menu");
const menuScrim = document.querySelector(".menu-scrim");
const closeMenu = () => {
  document.body.classList.remove("menu-open");
  menuButton?.setAttribute("aria-expanded", "false");
  mobileMenu?.setAttribute("aria-hidden", "true");
  if (menuScrim) menuScrim.hidden = true;
};
const openMenu = () => {
  if (menuScrim) menuScrim.hidden = false;
  requestAnimationFrame(() => document.body.classList.add("menu-open"));
  menuButton?.setAttribute("aria-expanded", "true");
  mobileMenu?.setAttribute("aria-hidden", "false");
};
menuButton?.addEventListener("click", openMenu);
document.querySelector(".menu-close")?.addEventListener("click", closeMenu);
menuScrim?.addEventListener("click", closeMenu);
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeMenu();
    closeLightbox();
  }
  if (!lightbox?.hidden && event.key === "ArrowLeft") showGalleryImage(activeGalleryImage - 1);
  if (!lightbox?.hidden && event.key === "ArrowRight") showGalleryImage(activeGalleryImage + 1);
});

const header = document.querySelector(".site-header");
const updateHeader = () => header?.classList.toggle("is-scrolled", window.scrollY > 12);
updateHeader();
window.addEventListener("scroll", updateHeader, { passive: true });

const revealItems = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    entry.target.classList.add("is-visible");
    observer.unobserve(entry.target);
  }), { threshold: 0.1, rootMargin: "0px 0px -32px" });
  revealItems.forEach((item) => observer.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}
